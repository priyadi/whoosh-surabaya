// Exercise the interactive parts in headless Chrome.
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import path from "node:path";
const require = createRequire(path.join(execSync("npm root -g").toString().trim(), "x.js"));
const puppeteer = require("puppeteer");
const browser = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome-stable", headless: "new", args: ["--no-sandbox"] });
const page = await browser.newPage(); await page.setViewport({ width: 1500, height: 1000 });
const errs = []; page.on("pageerror", e => errs.push(e.message)); page.on("console", m => { if (m.type() === "error") errs.push(m.text()); });
await page.goto("file://" + path.resolve("index.html"), { waitUntil: "load" });
const time = () => page.$eval(".tile .v", e => e.innerText);
const wait = ms => new Promise(r => setTimeout(r, ms));
console.log("baseline", await time());
await page.click('#map [data-toggle="pekalongan"]'); console.log("after map click on Pekalongan", await time(), await page.$eval("#stopCount", e => e.innerText));
await page.click('#stopList input[data-stop="karawang"]'); console.log("after Karawang checkbox", await time());
await page.click("#stopsNone"); console.log("express", await time());
await page.select("#preset", "4"); console.log("sceptic preset", await time(), "|", await page.$eval("#overall .big", e => e.innerText));
await wait(400); console.log("url", await page.evaluate(() => location.search));
await page.$eval("#spHit", e => e.scrollIntoView({ block: "center" })); await wait(200);
const box = await (await page.$("#spHit")).boundingBox();
await page.mouse.move(box.x + box.width * 0.55, box.y + box.height * 0.5); await wait(100);
console.log("tip:", await page.$eval("#tip", e => e.style.display + " | " + e.innerText.replace(/\n/g, " / ")), "| train marker:", await page.$eval("#mapTrain", e => e.style.display + " " + e.getAttribute("cx")));
await page.click('.vcard .ref'); console.log("modal:", await page.$eval("#modal", e => e.style.display), await page.$eval("#mtitle", e => e.innerText), await page.$$eval("#mlist li", l => l.length), "links");
await page.keyboard.press("Escape");
await page.$eval("#in_offset", e => e.click()); console.log("offset on → CO2 tile:", await page.$$eval(".tile", t => t[4].innerText.replace(/\n/g, " | ")));
await page.click("#resetAll"); await wait(400); console.log("reset", await time(), "url=[" + await page.evaluate(() => location.search) + "]");
console.log("errors:", errs.length ? errs : "none");
await page.setViewport({ width: 420, height: 900 }); await wait(300);
await page.screenshot({ path: "/tmp/whoosh-mobile.png", clip: { x: 0, y: 2300, width: 420, height: 1500 } });
console.log("mobile overflow px:", await page.evaluate(() => document.documentElement.scrollWidth - innerWidth));
await browser.close();
